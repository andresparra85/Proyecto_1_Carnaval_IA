/**
 * Evalúa si una consulta del usuario está relacionada con el Carnaval de Pasto.
 * @param {string} text - Consulta del usuario.
 * @returns {boolean} true si pertenece a la temática del Carnaval.
 */
export function isCarnavalRelatedQuery(text = '') {
  if (!text || typeof text !== 'string') return false;
  const clean = text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');

  // Permitir saludos o expresiones de cortesía comunes
  if (/^(hola|buenos dias|buenas tardes|buenas noches|que tal|como estas|quien eres|ayuda|gracias)/i.test(clean)) {
    return true;
  }

  // Verificar presencia de algún término temático
  return CARNAVAL_THEMATIC_TERMS.some((term) => {
    const cleanTerm = term.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    return clean.includes(cleanTerm);
  });
}

/**
 * Busca si la consulta coincide con algún día de la agenda del Carnaval.
 * @param {string} text - Consulta del usuario.
 * @returns {object|null} Configuración del día o null.
 */
export function findCarnavalDayAgenda(text = '') {
  if (!text || typeof text !== 'string') return null;
  const clean = text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');

  // Orden de evaluación priorizando patrones específicos
  const dayOrder = ['28', '31', '2', '3', '4', '5', '6', '7'];
  for (const dayKey of dayOrder) {
    const day = CARNAVAL_DAYS_AGENDA[dayKey];
    for (const kw of day.keywords) {
      const cleanKw = kw.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
      const regex = new RegExp(`\\b${cleanKw}\\b`, 'i');
      if (regex.test(clean) || clean.includes(cleanKw)) {
        return day;
      }
    }
  }

  // Coincidencias temáticas por palabras clave del desfile
  if (clean.includes('magno') || clean.includes('carroza')) return CARNAVAL_DAYS_AGENDA['6'];
  if (clean.includes('familia') || clean.includes('castaneda')) return CARNAVAL_DAYS_AGENDA['4'];
  if (clean.includes('coreografico') || clean.includes('tierra')) return CARNAVAL_DAYS_AGENDA['3'];
  if (clean.includes('infantil')) return CARNAVAL_DAYS_AGENDA['2'];
  if (clean.includes('negro') || clean.includes('pintica')) return CARNAVAL_DAYS_AGENDA['5'];
  if (clean.includes('cuy') || clean.includes('gastronom')) return CARNAVAL_DAYS_AGENDA['7'];
  if (clean.includes('asfalto') || clean.includes('tiza')) return CARNAVAL_DAYS_AGENDA['28'];
  if (clean.includes('ano viejo') || clean.includes('anos viejos')) return CARNAVAL_DAYS_AGENDA['31'];

  return null;
}

